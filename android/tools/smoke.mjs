await p.waitForTimeout(600);
await p.screenshot({path:'build/s1-today.png',fullPage:true});
console.log('tasks', await p.locator('.task').count(), 'banners', await p.locator('.banner').count());
await p.locator('[data-act=smaller]').first().click(); await p.waitForTimeout(300);
await p.screenshot({path:'build/s2-smaller.png'});
await p.locator('#sm-apply').click();
await p.locator('.task:not(.done) [data-act=check]').first().click(); await p.waitForTimeout(150);
await p.screenshot({path:'build/s3-cheer.png'});
await p.locator('[data-act=pulse][data-a=hard]').first().click();
